create extension if not exists pgcrypto;

create table public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    full_name text not null,
    phone text,
    barrio text,
    role text not null default 'citizen'
        check (role in ('citizen', 'admin')),
    created_at timestamptz not null default now()
);

create table public.incident_categories (
    id bigint generated by default as identity primary key,
    name text not null unique,
    description text,
    created_at timestamptz not null default now()
);

create table public.reports (
    id uuid primary key default gen_random_uuid(),
    report_code text not null unique default (
        'GRIU-' || to_char(now(), 'YYYY') || '-' ||
        upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8))
    ),
    reporter_id uuid not null references public.profiles(id),
    category_id bigint not null references public.incident_categories(id),
    title text not null,
    description text not null,
    barrio text not null,
    commune text,
    address text,
    latitude numeric,
    longitude numeric,
    status text not null default 'submitted'
    check (status in (
        'submitted',
        'in_review',
        'assigned',
        'in_progress',
        'resolved',
        'rejected'
    )),
    priority text not null default 'medium'
        check (priority in ('low', 'medium', 'high')),
    assigned_to uuid references public.profiles(id),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table public.report_updates (
    id uuid primary key default gen_random_uuid(),
    report_id uuid not null references public.reports(id) on delete cascade,
    changed_by uuid not null references public.profiles(id),
    old_status text,
    new_status text not null,
    note text,
    created_at timestamptz not null default now()
);

create table public.report_attachments (
    id uuid primary key default gen_random_uuid(),
    report_id uuid not null references public.reports(id) on delete cascade,
    uploaded_by uuid not null references public.profiles(id),
    storage_path text not null,
    file_name text not null,
    content_type text,
    created_at timestamptz not null default now()
);

